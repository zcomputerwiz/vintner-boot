package grubenv

import (
	"bytes"
	"errors"
	"io"
	"os"
	"strings"
)

// ErrFirstSector is returned if the environment block would exceed 512 bytes before padding.
var ErrFirstSector = errors.New("grubenv: environment block too large (must fit in 512 bytes)")

const blockSize = 1024
const headerLine = "# GRUB Environment Block\n"
const warningLine = "# WARNING: Do not edit this file by tools other than grub-editenv!!!\n"

// Env represents an ordered sequence of variables in a GRUB environment block.
type Env struct {
	keys   []string
	values []string
}

// Read loads a GRUB environment block from path. It parses the way GRUB's
// grub_envblk_iterate does: "#" starts a comment line, a backslash escapes
// the next byte, and a value ends at the first unescaped newline.
func Read(path string) (*Env, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	if len(data) != blockSize {
		return nil, errors.New("grubenv: file size is not exactly 1024 bytes")
	}
	if !bytes.HasPrefix(data, []byte(headerLine)) {
		return nil, errors.New("grubenv: invalid header")
	}
	if data[blockSize-1] != '#' {
		return nil, errors.New("grubenv: no padding")
	}

	env := &Env{}
	p := data[len(headerLine):]
	for len(p) > 0 {
		if p[0] == '#' || p[0] == '\n' {
			nl := bytes.IndexByte(p, '\n')
			if nl < 0 {
				break
			}
			p = p[nl+1:]
			continue
		}
		eq := bytes.IndexByte(p, '=')
		if eq < 0 {
			return nil, errors.New("grubenv: variable without '='")
		}
		name := string(p[:eq])
		var val []byte
		i := eq + 1
		for ; i < len(p) && p[i] != '\n'; i++ {
			if p[i] == '\\' && i+1 < len(p) {
				i++
			}
			val = append(val, p[i])
		}
		if i == len(p) {
			return nil, errors.New("grubenv: unterminated value")
		}
		env.Set(name, string(val))
		p = p[i+1:]
	}
	return env, nil
}

// Get returns the value of the named variable.
func (e *Env) Get(name string) (string, bool) {
	for i, k := range e.keys {
		if k == name {
			return e.values[i], true
		}
	}
	return "", false
}

// Set sets or updates the value of the named variable.
func (e *Env) Set(name, value string) {
	for i, k := range e.keys {
		if k == name {
			e.values[i] = value
			return
		}
	}
	e.keys = append(e.keys, name)
	e.values = append(e.values, value)
}

// Unset removes the named variable.
func (e *Env) Unset(name string) {
	for i, k := range e.keys {
		if k == name {
			e.keys = append(e.keys[:i], e.keys[i+1:]...)
			e.values = append(e.values[:i], e.values[i+1:]...)
			return
		}
	}
}

// Write saves the environment block back to path in-place.
func Write(path string, e *Env) error {
	var buf bytes.Buffer
	buf.WriteString(headerLine)
	buf.WriteString(warningLine)

	for i, k := range e.keys {
		v := e.values[i]
		v = strings.ReplaceAll(v, "\\", "\\\\")
		v = strings.ReplaceAll(v, "\n", "\\\n")
		buf.WriteString(k)
		buf.WriteByte('=')
		buf.WriteString(v)
		buf.WriteByte('\n')
	}

	if buf.Len() > 512 {
		return ErrFirstSector
	}

	// Pad with #
	padLen := blockSize - buf.Len()
	for i := 0; i < padLen; i++ {
		buf.WriteByte('#')
	}

	// Write in place
	info, err := os.Stat(path)
	if err != nil {
		return err
	}
	if info.Size() != blockSize {
		return errors.New("grubenv: file size is not exactly 1024 bytes")
	}

	f, err := os.OpenFile(path, os.O_WRONLY, 0)
	if err != nil {
		return err
	}
	defer f.Close()

	n, err := f.Write(buf.Bytes())
	if err != nil {
		return err
	}
	if n != blockSize {
		return io.ErrShortWrite
	}

	return f.Sync()
}
