func TestMissingWarningLine(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "grubenv")

	var buf bytes.Buffer
	buf.WriteString("# GRUB Environment Block\n")
	buf.WriteString("A=1\n")
	padLen := blockSize - buf.Len()
	for i := 0; i < padLen; i++ {
		buf.WriteByte('#')
	}

	if err := os.WriteFile(path, buf.Bytes(), 0644); err != nil {
		t.Fatal(err)
	}

	env, err := Read(path)
	if err != nil {
		t.Fatalf("failed to read missing warning line: %v", err)
	}

	v, ok := env.Get("A")
	if !ok || v != "1" {
		t.Errorf("A = %q, want 1", v)
	}
}

func TestInodeStability(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "grubenv")

	dummy := bytes.Repeat([]byte{'#'}, blockSize)
	if err := os.WriteFile(path, dummy, 0644); err != nil {
		t.Fatal(err)
	}

	info1, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}
	stat1 := info1.Sys().(*syscall.Stat_t)

	env := &Env{}
	env.Set("X", "1")
	if err := Write(path, env); err != nil {
		t.Fatal(err)
	}

	info2, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}
	stat2 := info2.Sys().(*syscall.Stat_t)

	if stat1.Ino != stat2.Ino {
		t.Errorf("inode changed: %d -> %d", stat1.Ino, stat2.Ino)
	}
}
