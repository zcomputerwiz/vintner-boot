func TestReadWriteRoundtrip(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "grubenv")

	// Create a dummy 1024 byte file
	dummy := bytes.Repeat([]byte{'#'}, blockSize)
	if err := os.WriteFile(path, dummy, 0644); err != nil {
		t.Fatal(err)
	}

	env := &Env{}
	env.Set("A", "back\\slash")
	env.Set("B", "two\nlines")
	env.Set("C", "plain")
	env.Set("D", "end_with_backslash\\")

	if err := Write(path, env); err != nil {
		t.Fatalf("Write failed: %v", err)
	}

	readEnv, err := Read(path)
	if err != nil {
		t.Fatalf("Read failed: %v", err)
	}

	a, ok := readEnv.Get("A")
	if !ok || a != "back\\slash" {
		t.Errorf("A = %q, want back\\slash", a)
	}

	b, ok := readEnv.Get("B")
	if !ok || b != "two\nlines" {
		t.Errorf("B = %q, want two\\nlines", b)
	}

	c, ok := readEnv.Get("C")
	if !ok || c != "plain" {
		t.Errorf("C = %q, want plain", c)
	}

	d, ok := readEnv.Get("D")
	if !ok || d != "end_with_backslash\\" {
		t.Errorf("D = %q, want end_with_backslash\\", d)
	}
}

func TestExactFixture(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "grubenv")

	dummy := bytes.Repeat([]byte{'#'}, blockSize)
	if err := os.WriteFile(path, dummy, 0644); err != nil {
		t.Fatal(err)
	}

	env := &Env{}
	env.Set("A", "back\\slash")
	env.Set("B", "two\nlines")
	env.Set("C", "plain")

	if err := Write(path, env); err != nil {
		t.Fatalf("Write failed: %v", err)
	}

	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}

	var expected bytes.Buffer
	expected.WriteString("# GRUB Environment Block\n")
	expected.WriteString("# WARNING: Do not edit this file by tools other than grub-editenv!!!\n")
	expected.WriteString("A=back\\\\slash\n")
	expected.WriteString("B=two\\\nlines\n")
	expected.WriteString("C=plain\n")
	padLen := blockSize - expected.Len()
	for i := 0; i < padLen; i++ {
		expected.WriteByte('#')
	}

	if !bytes.Equal(data, expected.Bytes()) {
		t.Errorf("Write did not match exact fixture")
	}
}

